import type { MetadataRoute } from "next";

/**
 * ما يُسمح لمحرّكات البحث برؤيته.
 *
 * **حزامٌ فوق حزام.** في `layout.tsx` وسمُ `noindex` على كل صفحة، وهو
 * الحارس الحقيقي — لكن بعض الزواحف تقرأ `robots.txt` ولا تصل إلى
 * الصفحة أصلاً لتقرأ وسمها. فالملفّان معاً لا واحد.
 *
 * **وهذا ليس ما يحمي الإدارة.** من كتب العنوان بيده يصل إليه مهما قال
 * هذا الملفّ — الحارس هو الاسم والرمز والقفل بعد خمس محاولات. غرض
 * هذا الملفّ أضيق: ألّا تُفهرس صفحةُ دخولٍ في جوجل فيعثر عليها من لم
 * يكن يبحث عنها.
 *
 * ويوم يريد المالك أن يجد الناسُ منيوه في البحث، يُسمح `/menu` وحده
 * هنا ويُرفع `noindex` عنه في `layout` — والباقي يبقى محجوباً.
 */
export default function robots(): MetadataRoute.Robots {
  return {
    rules: {
      userAgent: "*",
      disallow: "/",
    },
  };
}
