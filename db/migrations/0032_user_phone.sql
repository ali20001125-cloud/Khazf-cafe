-- =====================================================================
-- 0032 · هاتف الموظف · والرمز بيد المالك وحده
--
-- الرمز ليس كلمة سرٍّ يملكها صاحبها، بل **مفتاح توقيع**: به يُوافَق على
-- الإلغاء وبه يُنسَب كل فعلٍ لفاعله. وموظفٌ يبدّل مفتاحه بنفسه يكسر
-- سلسلةً كان المالك طرفها: مَن أعطى هذا الرمز؟ لا أحد يعرف بعدها.
--
-- فالحساب يُنشئه المالك: اسمٌ وهاتفٌ ورمزٌ يضعه هو. والهاتف هوية الشخص
-- خارج النظام — لا يُدخَل به، بل يُعرَف به عند الحاجة (من هذا «علي»
-- الذي أغلق وردية أمس؟).
-- =====================================================================

alter table users add column if not exists phone text;

comment on column users.phone is
  'هاتف الموظف — للتعريف والتواصل لا للدخول. الدخول باسمٍ يُختار ورمزٍ يضعه المالك.';

-- هاتفان متطابقان لموظفَين يجعلان «صاحب هذا الرقم» سؤالاً بلا جواب.
-- والفهرس جزئي: الفارغ مسموحٌ ومتكرّر، فالهاتف اختياري.
create unique index if not exists uq_users_phone
  on users(business_id, phone) where phone is not null;
