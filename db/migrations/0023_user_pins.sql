-- 0023 · الرموز: متى تغيّرت
--
-- الخلل المكتشف على القاعدة الحيّة: رمز المالك لا يزال **1111** ورمز
-- الباريستا **0000** — الرمزان الافتراضيان من `seed.sql`. وتعليق الملف
-- يقول «تُغيَّر فوراً من اللوحة»، لكن اللوحة لا تحتوي شاشةً تغيّرهما،
-- فبقيا كما هما.
--
-- وهذا ليس خطأ دخولٍ فقط: **رمز المالك هو نفسه رمز الموافقة** على إلغاء
-- فاتورة مدفوعة وعلى إرجاع المال. من يجرّب 1111 يفتح باب المال كلّه.
--
-- ما تضيفه هذه الهجرة عمود واحد: `pin_changed_at`. فارغٌ يعني «لم يُغيَّر
-- بعد»، فتعرضه اللوحة تحذيراً أحمر لا يزول إلا بالتغيير — لأن ما لا يُرى
-- لا يُعمل به، وهذا بالضبط ما حصل للتعليق في `seed.sql`.
--
-- ولماذا لا مُشغّل يمنع تشابه رمزين؟ المنع مطلوب — الرمز عندنا هويّة، وهو
-- ما يُثبت من وافق على الإلغاء، فلو تشابه رمزان لصار «من فعلها؟» سؤالاً
-- بلا جواب. لكن القاعدة لا تخزّن إلا التهشير، فلا تستطيع المقارنة إلا لو
-- مرّرنا لها الرمز الصريح (`set local`) — وذلك يكتب الرمز في سجلات
-- Postgres. الفحص في `src/app/manage/users-actions.ts` حيث الرمز الصريح
-- موجود أصلاً ولا يُكتب في أي سجلّ.
-- =====================================================================

alter table users add column if not exists pin_changed_at timestamptz;

comment on column users.pin_changed_at is
  'متى غُيّر الرمز آخر مرّة. فارغ = ما زال الرمز الافتراضي، وتُحذّر منه اللوحة.';
