/**
 * متى يكون رقم الجرد مشبوهاً؟
 *
 * قال المالك: «مستحيل يكون المخزون موجباً، فنرفض كل زيادة». وحدْسه صحيح
 * — الزيادة شاذّة — لكن القاعدة بالإشارة تُخطئ من الطرفين:
 *
 *   • **تمنع الصحيح**: بنٌّ بقي في المطحنة ولم يُعدّ أمس فظهر اليوم، أو
 *     شراءٌ نُسي تسجيله. كلاهما يرفع العدّ فوق المتوقّع بلا أن يكذب أحد.
 *   • **وتفوتها الأخطاء**: من أمثلته الثلاثة على متوقّعٍ ٥٬٤٠٠ — 54000
 *     و4500 و540 — اثنان **أقلّ** من المتوقّع، فتمرّ بلا وقفة.
 *
 * فالمسطرة الصحيحة ليست الإشارة بل المقدار مقيساً على **ما تحرّك**: لا
 * يضيع من المخزون أكثر ممّا مرّ منه. باع ٣٦٠ غ وأهدر ٤٠ ⇒ أقصى فرقٍ
 * معقول بضع مئات، لا آلاف.
 */
export type GuardInput = {
  counted: number;
  expected: number;
  /** ما خرج منذ آخر عدّة: بيعاً وهدراً ومشروبَ موظّف. */
  moved: number;
};

export function isSuspiciousCount({ counted, expected, moved }: GuardInput): boolean {
  if (!Number.isFinite(counted) || counted < 0) return false;
  // بلا حركةٍ مسجّلة لا مسطرة، فنرجع لنسبةٍ من الرصيد
  const allowed = moved > 0 ? moved * 2 + 100 : Math.max(expected * 0.5, 500);
  return Math.abs(counted - expected) > allowed;
}
