-- 0038 · البنّ العالق في المطحنة
--
-- قال المالك: «الوزن الذي في الهوبر ولا ينشال — أقيسه مرّة واحدة أوّل ما
-- أعبّي، وبعدها كل مرّة أجمعه مع ما تبقّى». وهي طريقة المقاهي نفسها:
-- تارةٌ ثابتة تُقاس مرّةً وتُضاف دائماً.
--
-- ولماذا يُخزَّن الرقم أصلاً: الرصيد يشمل هذا البنّ — دُفع ثمنه وهو
-- موجود — فمن يعدّ ما يُسكب وحده ينقص عدّه بمقداره كل مرّة، ويظهر فرقٌ
-- ثابت لا سبب له. ورقمٌ يُحفظ في الرأس يُنسى في أوّل ليلةٍ متعبة، فيُحفظ
-- هنا ويُذكَّر به في شاشة الجرد لحظة العدّ.
--
-- ولا يُضاف تلقائياً إلى المعدود: المالك قال «أجمعه» — فالجمع بيده،
-- والنظام يذكّر لا يفترض. وما يُفترض عن المستخدم يُحسب مرّتين يوماً ما.
-- =====================================================================

alter table materials
  add column if not exists hopper_grams integer not null default 0;

alter table materials drop constraint if exists materials_hopper_chk;
alter table materials
  add constraint materials_hopper_chk check (hopper_grams >= 0);

comment on column materials.hopper_grams is
  'ما يبقى عالقاً في المطحنة ولا يُسكب — يُقاس مرّةً ويُضاف لكل عدّة. تذكيرٌ في شاشة الجرد، لا إضافةٌ تلقائية.';
